import type { Metadata } from "next";
import { Inter, Geist_Mono } from "next/font/google";
import { connection } from "next/server";
import { Suspense, type ReactNode } from "react";
import { ConvexAuthNextjsServerProvider } from "@convex-dev/auth/nextjs/server";
import { ConvexClientProvider } from "./ConvexClientProvider";
import { Navbar } from "@/components/navbar";
import "./globals.css";

const inter = Inter({
  variable: "--font-inter",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "officeworker",
  description: "Generated by create next app",
};

async function ConvexAuthServerBoundary({ children }: { children: ReactNode }) {
  // Convex Auth's server provider reads request state and captures Date.now().
  // Keep it out of the prerendered shell when Cache Components is enabled.
  await connection();

  return (
    <ConvexAuthNextjsServerProvider>
      <ConvexClientProvider>{children}</ConvexClientProvider>
    </ConvexAuthNextjsServerProvider>
  );
}

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${inter.variable} ${geistMono.variable} h-full antialiased scroll-smooth motion-reduce:scroll-auto`}
    >
      <body className="min-h-full flex flex-col">
        <Navbar />
        <Suspense
          fallback={
            <div
              aria-hidden="true"
              className="min-h-svh flex-1 animate-pulse bg-app-bg"
            >
              <div className="mx-auto flex h-full max-w-6xl flex-col gap-6 px-4 pt-20 sm:px-6">
                <div className="h-8 w-48 rounded-lg bg-[#e5e5e7]" />
                <div className="h-4 w-80 rounded bg-[#ededef]" />
                <div className="mt-4 h-64 rounded-xl bg-[#f3f3f4]" />
              </div>
            </div>
          }
        >
          <ConvexAuthServerBoundary>{children}</ConvexAuthServerBoundary>
        </Suspense>
      </body>
    </html>
  );
}
